logger = logging.getLogger(__name__)

OUTPUTS_DIR = Path(os.getenv("OUTPUTS_DIR", "./outputs"))


def _write_docx(content: str, is_grounded: bool, filename: str) -> str:
    doc = Document()
    if not is_grounded:
        # Prepend a visible warning so the operator cannot miss it
        warning_para = doc.add_paragraph()
        run = warning_para.add_run(
            "Ã¢Å¡Â  LOW CONFIDENCE Ã¢â‚¬â€ Output may not be fully grounded in retrieved sources. Verify before use."
        )
        run.bold = True
        run.font.color.rgb = None  # Default to doc theme; can be styled further
        doc.add_paragraph("")

    doc.add_heading("Project Midas Output", 0)
    doc.add_paragraph(content)
    path = OUTPUTS_DIR / filename
    doc.save(str(path))
    return str(path)


def _write_xlsx(content: str, is_grounded: bool, filename: str) -> str:
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "Midas Output"

    if not is_grounded:
        ws.cell(row=1, column=1, value="Ã¢Å¡Â  LOW CONFIDENCE Ã¢â‚¬â€ Verify before use.")
        start_row = 2
    else:
        start_row = 1

    # Write content lines as rows
    for i, line in enumerate(content.splitlines()):
        ws.cell(row=start_row + i, column=1, value=line)

    path = OUTPUTS_DIR / filename
    wb.save(str(path))
    return str(path)

def _write_pdf(content: str, is_grounded: bool, filename: str) -> str:
    from fpdf import FPDF
    pdf = FPDF()
    pdf.add_page()
    pdf.set_font("helvetica", size=12)
    
    if not is_grounded:
        pdf.set_text_color(255, 0, 0)
        pdf.cell(0, 10, "⚠️ LOW CONFIDENCE — Verify before use.", new_x="LMARGIN", new_y="NEXT")
        pdf.set_text_color(0, 0, 0)
        pdf.ln(5)
        
    pdf.set_font("helvetica", style="B", size=16)
    pdf.cell(0, 10, "Project Midas Output", new_x="LMARGIN", new_y="NEXT")
    pdf.ln(5)
    
    pdf.set_font("helvetica", size=11)
    pdf.multi_cell(0, 8, content)
    
    path = OUTPUTS_DIR / filename
    pdf.output(str(path))
    return str(path)

def generate_pptx(title: str, sections: list[dict]) -> BytesIO:
    prs = Presentation()
    
    # Title slide
    title_slide_layout = prs.slide_layouts[0]
    slide = prs.slides.add_slide(title_slide_layout)
    title_shape = slide.shapes.title
    subtitle = slide.placeholders[1]
    title_shape.text = title
    subtitle.text = "Generated by Project Midas"

    # Body slides
    bullet_slide_layout = prs.slide_layouts[1]
    for section in sections:
        slide = prs.slides.add_slide(bullet_slide_layout)
        shapes = slide.shapes
        title_shape = shapes.title
        body_shape = shapes.placeholders[1]
        
        title_shape.text = section.get("title", "")
        if body_shape.has_text_frame:
            body_shape.text = section.get("content", "")
    
    pptx_io = BytesIO()
    prs.save(pptx_io)
    pptx_io.seek(0)
    return pptx_io


