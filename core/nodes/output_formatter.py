def format_output(state: MidasState) -> MidasState:
    """
    Node: format_output
    Writes the final output file and records the audit log entry.
    """
    task_id = state["task_id"]
    intent = state.get("intent", "document")
    is_grounded = state.get("is_grounded", True)
    content = state.get("execution_result", "").strip()
    start_time = state.get("_start_time", datetime.now(timezone.utc).timestamp())
    prompt = state.get("prompt", "").lower()

    OUTPUTS_DIR.mkdir(parents=True, exist_ok=True)
    file_id = str(uuid.uuid4())[:8]
    timestamp = datetime.now(timezone.utc).strftime("%Y%m%d_%H%M%S")

    is_presentation = False
    is_pdf = False
    if "pdf" in prompt:
        is_pdf = True
    elif intent in ("document", "vision"):
        if any(kw in prompt for kw in ["slide", "pptx", "presentation"]):
            is_presentation = True

    try:
        if intent == "chat":
            # STANDARD_CHAT generates no file; it's a direct conversational reply.
            output_path = None
            filename = None
            publish(task_id, "result", "Chat response complete.")
        elif state.get("flowchart_path"):
            output_path = state["flowchart_path"]
            filename = Path(output_path).name
            logger.info(f"[{task_id}] Flowchart ready at {output_path}")
            publish(task_id, "result", f"Flowchart ready: {filename}")
        elif not content:
            # The AI script didn't print any text. Check if it created a file itself.
            output_path = None
            recent_files = []
            for f in OUTPUTS_DIR.glob("*"):
                if f.is_file() and "uploads" not in f.parts:
                    if (datetime.now(timezone.utc).timestamp() - f.stat().st_mtime) < 30:
                        recent_files.append(f)
            if recent_files:
                recent_files.sort(key=lambda x: x.stat().st_mtime, reverse=True)
                output_path = str(recent_files[0])
                logger.info(f"[{task_id}] Agent created its own file: {output_path}")
                publish(task_id, "result", f"Agent generated file: {recent_files[0].name}")
            else:
                logger.info(f"[{task_id}] No content printed and no file generated.")
                publish(task_id, "result", "Task executed successfully, but no output was produced.")
        elif is_presentation:
            filename = f"midas_{timestamp}_{file_id}.pptx"
            output_path = OUTPUTS_DIR / filename
            
            title = "Project Midas Output"
            if not is_grounded:
                title += " (⚠️ LOW CONFIDENCE)"
                
            sections = [{"title": "Output", "content": content}]
            
            try:
                pptx_io = generate_pptx(title, sections)
                with open(output_path, "wb") as f:
                    f.write(pptx_io.getvalue())
                
                output_path = str(output_path)
                logger.info(f"[{task_id}] Output written to {output_path}")
                publish(task_id, "result", f"Output file ready: {filename}")
            except Exception as ppt_err:
                logger.warning(f"[{task_id}] PPTX generation failed ({ppt_err}), falling back to DOCX")
                filename = f"midas_{timestamp}_{file_id}.docx"
                output_path = _write_docx(content, is_grounded, filename)
                logger.info(f"[{task_id}] Output written to {output_path}")
                publish(task_id, "result", f"Output file ready: {filename} (fallback)")
        elif is_pdf:
            filename = f"midas_{timestamp}_{file_id}.pdf"
            output_path = _write_pdf(content, is_grounded, filename)
            logger.info(f"[{task_id}] Output written to {output_path}")
            publish(task_id, "result", f"Output file ready: {filename}")
        elif any(kw in prompt for kw in ["file", "document", "docx", "word", "excel", "xlsx", "spreadsheet", "report", "download"]):
            if intent == "math" or "excel" in prompt or "xlsx" in prompt or "spreadsheet" in prompt:
                filename = f"midas_{timestamp}_{file_id}.xlsx"
                output_path = _write_xlsx(content, is_grounded, filename)
                logger.info(f"[{task_id}] Output written to {output_path}")
                publish(task_id, "result", f"Output file ready: {filename}")
            else:
                filename = f"midas_{timestamp}_{file_id}.docx"
                output_path = _write_docx(content, is_grounded, filename)
                logger.info(f"[{task_id}] Output written to {output_path}")
                publish(task_id, "result", f"Output file ready: {filename}")
        else:
            # User didn't ask for a file, just show the text output like Gemini.
            output_path = None
            publish(task_id, "result", "Task executed successfully.")
    except Exception as e:
        logger.error(f"[{task_id}] Failed to write output file: {e}")
        output_path = None
        publish(task_id, "error", f"Output formatting failed: {e}")

    # Audit log Ã¢â‚¬â€ full structured entry (Phase 2 deliverable)
    duration_ms = int((datetime.now(timezone.utc).timestamp() - start_time) * 1000)
    log_audit_event({
        "task_id": task_id,
        "user_id_hash": state.get("user_id_hash", ""),
        "intent": intent,
        "result_type": "success",
        "output_path": output_path,
        "ground_score": state.get("ground_score"),
        "is_grounded": is_grounded,
        "iterations": state.get("iteration", 1),
        "duration_ms": duration_ms,
        "tier_b_dispatched": False,  # Tier A only for all agent-generated code
    })

    return {**state, "final_output_path": output_path}

